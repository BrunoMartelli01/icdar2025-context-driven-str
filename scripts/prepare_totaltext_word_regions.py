"""Prepare isolated curved-word Total-Text TRAIN targets; never alters source."""

from __future__ import annotations

import argparse
from dataclasses import asdict
import json
import os
from pathlib import Path
import shutil

from PIL import Image
import yaml

from recognition.scene_text_datasets import parse_totaltext_annotation
from segmentation.scene_text_preparation import file_sha256
from segmentation.totaltext_word_regions import make_word_regions


def _copy_or_link(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        if file_sha256(source) != file_sha256(destination):
            raise ValueError(f"Existing destination differs: {destination}")
        return
    try:
        os.link(source, destination)
    except OSError:
        shutil.copy2(source, destination)


def _save_checked(image: Image.Image, path: Path, *, allow_refresh: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        # Resume is safe only when regenerated bytes match.
        from io import BytesIO

        stream = BytesIO()
        image.save(stream, format="PNG")
        if path.read_bytes() != stream.getvalue():
            if not allow_refresh:
                raise ValueError(f"Existing generated target differs: {path}")
            image.save(path, format="PNG")
        return
    image.save(path, format="PNG")


def prepare(source_root: Path, output_root: Path, *, refresh_separation: bool = False) -> dict:
    source_root = source_root.resolve()
    output_root = output_root.resolve()
    source_manifest = source_root / "manifests/total_text_train.yaml"
    source = yaml.safe_load(source_manifest.read_text(encoding="utf-8"))
    if source.get("dataset") != "total_text" or source.get("split_role") != "train":
        raise ValueError("Expected official Total-Text TRAIN source manifest")
    if len(source["samples"]) != 1255:
        raise ValueError("Total-Text TRAIN must contain exactly 1255 images")
    records = []
    audits = []
    for offset, record in enumerate(source["samples"], 1):
        stem = record["id"].split(":")[-1]
        rel_image = Path(record["image"])
        rel_annotation = Path("datasets/total_text/train/annotations") / f"{stem}.txt"
        rel_validity = Path(record["validity_annotation"])
        source_image = source_root / rel_image
        source_annotation = source_root / rel_annotation
        if file_sha256(source_image) != record["image_sha256"]:
            raise ValueError(f"Source image checksum mismatch: {source_image}")
        _copy_or_link(source_image, output_root / rel_image)
        _copy_or_link(source_annotation, output_root / rel_annotation)
        with Image.open(source_image) as opened:
            size = opened.size
        target, validity, separator, owners, audit = make_word_regions(
            size, parse_totaltext_annotation(source_annotation)
        )
        if audit.empty_word_count:
            raise ValueError(f"Word disappeared in sample {record['id']}: {audit}")
        rel_mask = Path("datasets/total_text/train/masks") / f"{stem}.png"
        rel_separator = Path("datasets/total_text/train/separators") / f"{stem}.png"
        rel_owners = Path("datasets/total_text/train/owners") / f"{stem}.png"
        _save_checked(target, output_root / rel_mask)
        _save_checked(validity, output_root / rel_validity)
        _save_checked(separator, output_root / rel_separator, allow_refresh=refresh_separation)
        _save_checked(owners, output_root / rel_owners)
        records.append({
            "id": record["id"], "image": rel_image.as_posix(),
            "image_sha256": record["image_sha256"],
            "mask": rel_mask.as_posix(),
            "mask_sha256": file_sha256(output_root / rel_mask),
            "validity_annotation": rel_validity.as_posix(),
            "validity_annotation_sha256": file_sha256(output_root / rel_validity),
            "separation_annotation": rel_separator.as_posix(),
            "separation_annotation_sha256": file_sha256(output_root / rel_separator),
            "word_owner_annotation": rel_owners.as_posix(),
            "word_owner_annotation_sha256": file_sha256(output_root / rel_owners),
        })
        audits.append(asdict(audit))
        if offset % 100 == 0 or offset == len(source["samples"]):
            print(f"[curved-word target] {offset}/1255", flush=True)
    manifest = dict(source)
    manifest["split"] = "official-train-curved-word-regions-v1"
    manifest["acquisition"] = {
        "source_manifest_sha256": file_sha256(source_manifest),
        "classification": "ASSUMPTION",
        "overlap_policy": "nearest-exclusive-pixel-ownership-then-8-neighbour-separator",
    }
    manifest["annotation_policy"] = dict(source["annotation_policy"])
    manifest["annotation_policy"].update({
        "target_source": "totaltext_official_word_polygons_filled_disjoint",
        "target_classification": "ASSUMPTION",
        "separation_map": "original_raster_contact_pixels_zero_target",
    })
    manifest["samples"] = records
    manifest_path = output_root / "manifests/total_text_train.yaml"
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_bytes = yaml.safe_dump(manifest, sort_keys=False).encode("utf-8")
    if manifest_path.exists() and manifest_path.read_bytes() != manifest_bytes and not refresh_separation:
        raise ValueError(f"Existing manifest differs: {manifest_path}")
    manifest_path.write_bytes(manifest_bytes)
    report = {
        "classification": "PRACTICAL_APPROXIMATION",
        "source_manifest_sha256": file_sha256(source_manifest),
        "manifest_sha256": file_sha256(manifest_path),
        "images": len(records),
        "words": sum(item["word_count"] for item in audits),
        "curved_words": sum(item["curved_word_count"] for item in audits),
        "contested_pixels": sum(item["contested_pixels"] for item in audits),
        "removed_separator_pixels": sum(item["removed_separator_pixels"] for item in audits),
        "interword_gap_pixels": sum(item["interword_gap_pixels"] for item in audits),
        "minimum_retained_polygon_fraction_per_image": min(item["retained_polygon_fraction"] for item in audits),
        "empty_words": sum(item["empty_word_count"] for item in audits),
        "per_image": {record["id"]: item for record, item in zip(records, audits)},
    }
    report_path = output_root / "qualification.json"
    report_bytes = (json.dumps(report, sort_keys=True, indent=2) + "\n").encode("utf-8")
    if report_path.exists() and report_path.read_bytes() != report_bytes and not refresh_separation:
        raise ValueError(f"Existing qualification report differs: {report_path}")
    report_path.write_bytes(report_bytes)
    print("MANIFEST", manifest_path, file_sha256(manifest_path))
    print("QUALIFICATION", report_path, file_sha256(report_path))
    return report


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--refresh-separation", action="store_true")
    args = parser.parse_args()
    prepare(args.source_root, args.output_root, refresh_separation=args.refresh_separation)


if __name__ == "__main__":
    main()
